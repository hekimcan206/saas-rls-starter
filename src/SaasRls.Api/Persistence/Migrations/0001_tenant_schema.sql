-- Tenant data. Every relation in schema "app" is tenant-scoped and protected by row-level security; the startup guard
-- (RlsGuard) refuses to serve if one is not. Run as saas_migrator, which owns these tables: hence FORCE on every one.

-- The tenant of the current transaction, set by the application with set_config('app.tenant_id', $1, true).
--  * current_setting(..., true) returns NULL instead of raising when the setting was never defined in this session.
--  * nullif(..., ''): after a transaction that used SET LOCAL ends, or after RESET/DISCARD, a custom setting the
--    session has seen reads back as '' rather than NULL. ''::uuid would raise; NULL makes every comparison false.
-- Either way, no tenant means no rows and no writes (fail closed). A malformed value raises an error, also closed.
-- LANGUAGE sql + STABLE lets the planner inline it, so "tenant_id = app.current_tenant_id()" is an index condition.
CREATE FUNCTION app.current_tenant_id() RETURNS uuid
    LANGUAGE sql STABLE PARALLEL SAFE
    AS $$ SELECT nullif(pg_catalog.current_setting('app.tenant_id', true), '')::uuid $$;

CREATE TABLE app.tenants (
    id         uuid        PRIMARY KEY,
    name       text        NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    plan       text        NOT NULL DEFAULT 'free' CHECK (plan IN ('free', 'pro', 'enterprise')),
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Ids are UUIDs generated by the application (version 7), never a shared sequence: a global bigserial tells every
-- tenant how many rows all other tenants created between two of its own inserts.
CREATE TABLE app.customers (
    id         uuid        PRIMARY KEY,
    tenant_id  uuid        NOT NULL DEFAULT app.current_tenant_id() REFERENCES app.tenants (id) ON DELETE CASCADE,
    name       text        NOT NULL CHECK (length(name) BETWEEN 1 AND 200),
    email      text        NOT NULL CHECK (length(email) BETWEEN 3 AND 320),
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Target of the composite foreign key below.
    UNIQUE (tenant_id, id),
    -- Unique per tenant, not globally: a global unique index answers "does another tenant have this e-mail?" with a
    -- unique violation, even though RLS hides the row.
    UNIQUE (tenant_id, email)
);

CREATE TABLE app.orders (
    id          uuid        PRIMARY KEY,
    tenant_id   uuid        NOT NULL DEFAULT app.current_tenant_id(),
    customer_id uuid        NOT NULL,
    number      bigint      NOT NULL,
    status      text        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'paid', 'cancelled')),
    total_cents bigint      NOT NULL CHECK (total_cents >= 0),
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, number),
    -- Composite foreign key. Referential-integrity checks do not apply RLS, so a plain customer_id reference would let
    -- tenant A attach an order to tenant B's customer and, from the error or its absence, learn whether a guessed
    -- customer id exists anywhere. Including tenant_id makes a cross-tenant reference impossible.
    FOREIGN KEY (tenant_id, customer_id) REFERENCES app.customers (tenant_id, id) ON DELETE CASCADE
);

CREATE INDEX orders_tenant_created_idx ON app.orders (tenant_id, created_at DESC);
CREATE INDEX orders_tenant_customer_idx ON app.orders (tenant_id, customer_id);

-- Per-tenant, gap-tolerant document numbers (order 1, 2, 3 ... for every tenant) instead of a shared sequence.
CREATE TABLE app.tenant_counters (
    tenant_id uuid   NOT NULL DEFAULT app.current_tenant_id() REFERENCES app.tenants (id) ON DELETE CASCADE,
    name      text   NOT NULL,
    value     bigint NOT NULL,
    PRIMARY KEY (tenant_id, name)
);

-- ENABLE turns the policies on; FORCE makes them apply to the table owner too. Without FORCE, anything running as
-- saas_migrator (a view it owns, a SECURITY DEFINER function, a maintenance script) silently sees every tenant.
ALTER TABLE app.tenants ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.tenants FORCE ROW LEVEL SECURITY;
ALTER TABLE app.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.customers FORCE ROW LEVEL SECURITY;
ALTER TABLE app.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.orders FORCE ROW LEVEL SECURITY;
ALTER TABLE app.tenant_counters ENABLE ROW LEVEL SECURITY;
ALTER TABLE app.tenant_counters FORCE ROW LEVEL SECURITY;

-- One permissive policy per table for all commands. USING filters what can be seen, updated and deleted; WITH CHECK
-- rejects inserted or updated rows that would belong to another tenant ("new row violates row-level security policy").
CREATE POLICY tenant_isolation ON app.tenants
    USING (id = app.current_tenant_id())
    WITH CHECK (id = app.current_tenant_id());
CREATE POLICY tenant_isolation ON app.customers
    USING (tenant_id = app.current_tenant_id())
    WITH CHECK (tenant_id = app.current_tenant_id());
CREATE POLICY tenant_isolation ON app.orders
    USING (tenant_id = app.current_tenant_id())
    WITH CHECK (tenant_id = app.current_tenant_id());
CREATE POLICY tenant_isolation ON app.tenant_counters
    USING (tenant_id = app.current_tenant_id())
    WITH CHECK (tenant_id = app.current_tenant_id());

-- security_invoker: the view is evaluated with the caller's rights, so the caller's RLS policies apply. A default view
-- runs with its owner's rights and would hide nothing from anyone the owner can see.
CREATE VIEW app.customer_order_totals WITH (security_invoker = true) AS
SELECT c.tenant_id,
       c.id                           AS customer_id,
       c.name,
       count(o.id)                    AS orders,
       coalesce(sum(o.total_cents), 0)::bigint AS total_cents
FROM app.customers c
LEFT JOIN app.orders o ON o.tenant_id = c.tenant_id AND o.customer_id = c.id
GROUP BY c.tenant_id, c.id, c.name;

-- SECURITY INVOKER (the default): runs under the caller's policies.
CREATE FUNCTION app.next_number(p_name text) RETURNS bigint
    LANGUAGE sql VOLATILE
    AS $$
        INSERT INTO app.tenant_counters AS c (name, value) VALUES (p_name, 1)
        ON CONFLICT (tenant_id, name) DO UPDATE SET value = c.value + 1
        RETURNING c.value
    $$;

CREATE FUNCTION app.customer_lifetime_value(p_customer uuid) RETURNS bigint
    LANGUAGE sql STABLE
    AS $$ SELECT coalesce(sum(o.total_cents), 0)::bigint FROM app.orders o WHERE o.customer_id = p_customer $$;

-- Least privilege for the application role. UPDATE is granted per column and never on tenant_id or id: moving a row
-- between tenants is refused by the policy anyway, and the grant makes the intent explicit.
GRANT USAGE ON SCHEMA app TO saas_app;
GRANT SELECT ON app.tenants TO saas_app;
GRANT SELECT, INSERT, DELETE ON app.customers, app.orders TO saas_app;
GRANT UPDATE (name, email) ON app.customers TO saas_app;
GRANT UPDATE (status, total_cents) ON app.orders TO saas_app;
GRANT SELECT, INSERT, UPDATE (value) ON app.tenant_counters TO saas_app;
GRANT SELECT ON app.customer_order_totals TO saas_app;
GRANT EXECUTE ON FUNCTION app.current_tenant_id(), app.next_number(text), app.customer_lifetime_value(uuid) TO saas_app;
